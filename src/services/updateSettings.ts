export type UpdateSettings = { endpoint: string; publicKey: string }
export type UpdateInfo = { checkId: number; version: string; notes: string; date?: string }
export function validateUpdateSettings(settings: UpdateSettings, allowEmpty = true): UpdateSettings {
  const endpoint = settings.endpoint.trim(), publicKey = settings.publicKey.trim()
  if (allowEmpty && !endpoint && !publicKey) return { endpoint, publicKey }
  let url: URL
  try { url = new URL(endpoint) } catch { throw new Error('Enter a complete HTTPS update manifest URL.') }
  if (url.protocol !== 'https:' || url.username || url.password || url.hash) throw new Error('Update manifest must use HTTPS without credentials or a fragment.')
  let decoded: string
  try { if (publicKey.length > 4096) throw new Error(); decoded = atob(publicKey) } catch { throw new Error('Paste the public key generated by tauri signer.') }
  const lines = decoded.split(/\r?\n/).filter(line => line && !line.startsWith('untrusted comment:'))
  let key: string
  try { if (lines.length !== 1) throw new Error(); key = atob(lines[0]) } catch { throw new Error('Invalid updater public key.') }
  if (key.length !== 42 || !['Ed', 'ED'].includes(key.slice(0, 2))) throw new Error('Invalid updater public key.')
  return { endpoint, publicKey }
}
